# ...

#pip main work is on terminal not to code.

#simple chart to remember:
# pip install package
#         ↓
# Install package

# pip install --upgrade package
#         ↓
# Upgrade package

# pip install package==version
#         ↓
# Install specific version

# pip uninstall package
#         ↓
# Remove package

# pip list
#         ↓
# List all packages

# pip show package
#         ↓
# Details of one package