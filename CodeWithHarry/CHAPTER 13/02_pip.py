#pip: pip is Python's package manager, used to install, uninstall, upgrade, 
# and manage external Python packages and their dependencies.

#in python most of the packages are not buil-in, 
#so whenever we need any external library we install it using pip.

#pip install: It is used to install any package
# -> pip install package_name, for example(pip install numpy)

#pip list: It is used to see the list of installed packages in an environment.

#pip show: It is used to see and get information of any specific package -> pip show package_name
#It will give information like: name, version, location, dependencies

#pip uninstall: It is used to remove any package -> pip uninstall package_name
#after running pip uninstall for any package pip will ask for confirmation (Y/n)

